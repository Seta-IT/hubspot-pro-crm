/** Liga os contratos/faturas seed (desvinculados no seed) as propostas fixture, como antes. */
const FIXTURE_LINKS: Record<string, string> = {
  'ctr-loc-101': 'prop-fixture-001',
  'ctr-srv-104': 'prop-fixture-002',
  'ctr-sub-105': 'prop-fixture-003',
  'inv-loc-0001': 'prop-fixture-001',
  'inv-nfe-rem-0412': 'prop-fixture-001',
  'inv-nfse-0089': 'prop-fixture-002',
};

export function addLegacyFixtureProposals(repo: CrmRepository): CrmRepository {
  const erp = (repo as unknown as { ensureErp: () => ErpDatabaseState }).ensureErp();
  const have = new Set(erp.proposals.map((p) => p.id));
  for (const p of createLegacyFixtureProposals()) if (!have.has(p.id)) erp.proposals.push(p);
  for (const c of [...(erp.rentalContracts || []), ...(erp.invoices || [])] as Array<{ id: string; proposalId?: string | null }>) {
    const link = FIXTURE_LINKS[c.id];
    if (link && !c.proposalId) c.proposalId = link;
  }
  return repo;
}

/** Repositorio em memoria com o seed real + as propostas fixture (somente testes). */
export function createInMemoryRepository(initialState?: CrmDatabaseState): CrmRepository {
  const repo = createRealInMemoryRepository(initialState);
  return initialState ? repo : addLegacyFixtureProposals(repo);
}
